"""Ollama Cloud access for the frontier models.

Sovereign Code is local-first: nothing is routed to the internet unless the
user explicitly names a ``:cloud`` tag, a ``cloud-*`` gateway alias, or runs
``sovereign cloud --enable``. Ollama serves these models from ollama.com, so
prompts leave the Mac; the CLI says that before it does anything.

Two switches disable cloud access and both must be off:

* ``~/.ollama/server.json`` -> ``{"disable_ollama_cloud": true}`` (the app's
  persisted setting);
* ``OLLAMA_NO_CLOUD`` in the login/session environment (the launchd agent that
  tunes this Mac sets it to 1).

This module keeps the readiness checks and the gateway-config rendering pure so
they are testable. Only :func:`apply_cloud` and :func:`install_gateway_aliases`
touch the machine.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import time
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Any

from .config import LOCAL_AI_ROOT
from .models import CATALOG, CLOUD_PREFERENCE, CLOUD_TAGS, REQUESTED_CLOUD_MODELS

# A cloud model's 1M-token window is real, but 128k is a sane ceiling for a
# local coding client and keeps the gateway from forwarding absurd requests.
DEFAULT_ALIAS_CONTEXT = 131_072
LOCAL_ALIAS_CONTEXT = 32_768
PRO_UPGRADE = "https://ollama.com/upgrade"

# Alias -> Ollama tag. Stable names for clients, one per requested model plus
# two role aliases. `cloud-deepseek-v4-flash` follows the retired tag to the
# current DeepSeek Flash.
ALIAS_TARGETS: dict[str, str] = {
    "cloud-kimi-k3": "kimi-k3:cloud",
    "cloud-kimi-k2.6": "kimi-k2.6:cloud",
    "cloud-deepseek-v4.1-flash": "deepseek-v4.1-flash:cloud",
    "cloud-deepseek-v4-flash": "deepseek-v4.1-flash:cloud",
    "cloud-deepseek-v4-pro": "deepseek-v4-pro:cloud",
    "cloud-glm-5.3": "glm-5.3:cloud",
    "cloud-glm-5.3-flash": "glm-5.3-flash:cloud",
    "cloud-glm-5.2": "glm-5.2:cloud",
    "local-qwen3.8": "qwen3.8:27b",
    "local-cloud": "kimi-k3:cloud",
    "local-cloud-fast": "glm-5.3-flash:cloud",
}

BLOCK_START = "# >>> sovereign cloud aliases (generated by `sovereign cloud --install-aliases`)"
BLOCK_END = "# <<< sovereign cloud aliases"


def is_cloud_tag(tag: str) -> bool:
    """True for Ollama Cloud tags, including dated variants like `:1017-cloud`."""
    name = tag.strip().lower()
    return name.endswith(":cloud") or name.endswith("-cloud")


def cloud_disabled_hint(message: str) -> str:
    """Append the fix when Ollama says cloud is switched off."""
    text = str(message)
    if "cloud is disabled" not in text.lower():
        return text
    return f"{text} — enable it with: sovereign cloud --enable"


def plan_required(message: str) -> bool:
    """True when the account's Ollama plan does not include the model."""
    text = str(message).lower()
    return (
        "not in the free plan" in text
        or "free plan" in text
        or "free usage limit" in text
        or "ollama.com/upgrade" in text
        or ("upgrade" in text and "plan" in text)
    )


def plan_hint(message: str) -> str:
    """Explain a 402 instead of leaving a raw HTTP error in the terminal."""
    if not plan_required(message):
        return str(message)
    return (
        f"{message} — this model needs an Ollama Pro plan: {PRO_UPGRADE} "
        "(the app is wired correctly; the subscription is on the account)"
    )


def ollama_error_hint(message: str) -> str:
    """The one place both cloud errors get their actionable suffix."""
    return plan_hint(cloud_disabled_hint(message))


def server_json_path() -> Path:
    return Path.home() / ".ollama" / "server.json"


def launch_agent_paths() -> list[Path]:
    return [
        Path.home() / "Library" / "LaunchAgents" / "com.user.ollama.env.plist",
        LOCAL_AI_ROOT / "launchd" / "com.user.ollama.env.plist",
    ]


def _read_json(path: Path) -> dict[str, Any]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def server_cloud_disabled(path: Path | None = None) -> bool:
    """The app's persisted cloud toggle (a missing file means cloud is on)."""
    data = _read_json(path or server_json_path())
    value = data.get("disable_ollama_cloud", False)
    if isinstance(value, str):
        return value.strip().lower() in {"1", "true", "yes", "on"}
    return bool(value)


def _launchctl_getenv(name: str) -> str:
    try:
        result = subprocess.run(
            ["launchctl", "getenv", name], capture_output=True, text=True, check=False, timeout=5
        )
    except (OSError, subprocess.SubprocessError):
        return ""
    return result.stdout.strip()


_ENV_CACHE: tuple[float, bool] | None = None
_ENV_CACHE_SECONDS = 10.0


def _env_disabled(getter: Any) -> bool:
    try:
        value = getter("OLLAMA_NO_CLOUD")
    except Exception:
        return False
    return str(value or "").strip().lower() in {"1", "true", "yes", "on"}


def env_cloud_disabled(getenv: Any = None) -> bool:
    """True when OLLAMA_NO_CLOUD is set in the server's environment.

    The dashboard calls this every few seconds; `launchctl getenv` is a process
    spawn, so cache the launchd answer briefly. An injected getter (tests) is
    always evaluated directly.
    """
    global _ENV_CACHE
    if getenv is not None:
        return _env_disabled(getenv)
    now = time.monotonic()
    if _ENV_CACHE is not None and now - _ENV_CACHE[0] < _ENV_CACHE_SECONDS:
        return _ENV_CACHE[1]
    value = _env_disabled(_launchctl_getenv)
    _ENV_CACHE = (now, value)
    return value


def cloud_enabled(server_path: Path | None = None, getenv: Any = None) -> bool:
    return not server_cloud_disabled(server_path) and not env_cloud_disabled(getenv)


@dataclass(frozen=True)
class CloudStatus:
    enabled: bool
    server_disabled: bool
    env_disabled: bool

    @property
    def detail(self) -> str:
        if self.enabled:
            return "enabled"
        reasons = []
        if self.server_disabled:
            reasons.append("server.json disables cloud")
        if self.env_disabled:
            reasons.append("OLLAMA_NO_CLOUD is set")
        return "disabled (" + "; ".join(reasons) + ")"


def read_cloud_status(server_path: Path | None = None, getenv: Any = None) -> CloudStatus:
    server_disabled = server_cloud_disabled(server_path)
    env_disabled = env_cloud_disabled(getenv)
    return CloudStatus(
        enabled=not server_disabled and not env_disabled,
        server_disabled=server_disabled,
        env_disabled=env_disabled,
    )


def set_server_cloud(enabled: bool, path: Path | None = None) -> bool:
    """Write the app's cloud toggle. Returns True when the file changed."""
    target = path or server_json_path()
    data = _read_json(target)
    before = data.get("disable_ollama_cloud")
    data["disable_ollama_cloud"] = not enabled
    if before == data["disable_ollama_cloud"]:
        return False
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return True


def _rewrite_launch_agent(path: Path, enabled: bool) -> bool:
    """Set OLLAMA_NO_CLOUD in the login agent without dropping its comments.

    plistlib would round-trip the XML and lose every explanatory comment in the
    file, so edit the one shell token in place instead.
    """
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False
    value = "0" if enabled else "1"
    updated, count = re.subn(r"(setenv\s+OLLAMA_NO_CLOUD\s+)[01]", rf"\g<1>{value}", text)
    if count == 0:
        return False
    if updated == text:
        return False
    path.write_text(updated, encoding="utf-8")
    return True


def _set_launchctl_env(enabled: bool) -> None:
    global _ENV_CACHE
    _ENV_CACHE = None
    value = "0" if enabled else "1"
    try:
        subprocess.run(
            ["launchctl", "setenv", "OLLAMA_NO_CLOUD", value],
            check=False,
            timeout=5,
        )
    except (OSError, subprocess.SubprocessError):
        pass


def _wait_for_ollama(seconds: float = 20.0) -> bool:
    """Wait for the restarted server's port; never fail the command on a slow app."""
    from .system import port_open

    deadline = seconds
    while deadline > 0:
        if port_open("127.0.0.1", 11434):
            return True
        import time

        time.sleep(0.5)
        deadline -= 0.5
    return False


def apply_cloud(enabled: bool, restart: bool = True) -> list[str]:
    """Turn Ollama Cloud on/off persistently and restart the app.

    Returns human-readable actions that were performed, so the CLI can show
    exactly what changed (and tests can assert on the pure helpers instead).
    """
    actions: list[str] = []
    if set_server_cloud(enabled):
        actions.append(f"server.json: disable_ollama_cloud={not enabled}")
    _set_launchctl_env(enabled)
    actions.append(f"session: OLLAMA_NO_CLOUD={'0' if enabled else '1'}")
    for agent in launch_agent_paths():
        if agent.is_file() and _rewrite_launch_agent(agent, enabled):
            actions.append(f"login agent updated: {agent}")
    if restart:
        from .tune import restart_ollama

        # `open -a Ollama` hands the caller's environment to the app, so the
        # shell that runs this command can silently re-disable cloud with its
        # own OLLAMA_NO_CLOUD=1. Strip it for the restart, then put it back so
        # we do not mutate the caller's environment.
        previous = os.environ.pop("OLLAMA_NO_CLOUD", None)
        if not enabled:
            os.environ["OLLAMA_NO_CLOUD"] = "1"
        try:
            restart_ollama()
        finally:
            if enabled:
                os.environ.pop("OLLAMA_NO_CLOUD", None)
                if previous is not None:
                    os.environ["OLLAMA_NO_CLOUD"] = previous
        if _wait_for_ollama():
            actions.append("Ollama restarted with cloud " + ("on" if enabled else "off"))
        else:
            actions.append("Ollama restart requested (port not up yet)")
    return actions


@dataclass(frozen=True)
class GatewayAlias:
    alias: str
    tag: str
    context: int
    cloud: bool

    @property
    def model_line(self) -> str:
        return f"ollama/{self.tag}"


def gateway_aliases() -> list[GatewayAlias]:
    """The aliases `--install-aliases` writes, in a stable order."""
    rows: list[GatewayAlias] = []
    for alias, tag in ALIAS_TARGETS.items():
        spec = CATALOG.get(tag)
        if spec is None:
            continue
        context = (
            LOCAL_ALIAS_CONTEXT if not spec.cloud else min(DEFAULT_ALIAS_CONTEXT, spec.max_context)
        )
        rows.append(GatewayAlias(alias, tag, context, spec.cloud))
    return rows


def gateway_block() -> str:
    """A YAML model_list fragment for the cloud aliases."""
    lines = [
        f"  {BLOCK_START}",
        "  # Remote models: prompts leave this Mac. Remove this block to hide them.",
    ]
    for row in gateway_aliases():
        lines.extend(
            [
                f"  - model_name: {row.alias}",
                "    litellm_params:",
                f"      model: {row.model_line}",
                "      api_base: http://127.0.0.1:11434",
                f"      num_ctx: {row.context}",
            ]
        )
    lines.append(f"  {BLOCK_END}")
    return "\n".join(lines)


_BLOCK_RE = re.compile(
    rf"\n?^\s*{re.escape(BLOCK_START)}.*?^\s*{re.escape(BLOCK_END)}\n?",
    re.MULTILINE | re.DOTALL,
)


def merge_gateway_text(text: str, block: str | None = None) -> str:
    """Insert/replace the generated block without disturbing user entries."""
    body = block if block is not None else gateway_block()
    stripped = _BLOCK_RE.sub("\n", text)
    # The block must stay inside model_list, so insert before the next
    # top-level key rather than appending to the end of the document.
    for marker in ("\nrouter_settings:", "\nlitellm_settings:"):
        index = stripped.find(marker)
        if index != -1:
            head, tail = stripped[:index], stripped[index:]
            return head.rstrip("\n") + "\n" + body + "\n" + tail
    return stripped.rstrip("\n") + "\n" + body + "\n"


def gateway_config_paths() -> list[Path]:
    base = LOCAL_AI_ROOT / "gateway"
    names = ("config.yaml", "config.sovereign-recommended.yaml")
    return [base / name for name in names if (base / name).is_file()]


def install_gateway_aliases(paths: list[Path] | None = None) -> list[Path]:
    """Write the cloud aliases into the LiteLLM config(s), with a backup."""
    written: list[Path] = []
    targets = paths if paths is not None else gateway_config_paths()
    for path in targets:
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        updated = merge_gateway_text(text)
        if updated == text:
            written.append(path)
            continue
        backup = path.with_name(f"{path.name}.bak-{datetime.now():%Y%m%d-%H%M%S}")
        try:
            shutil.copy2(path, backup)
        except OSError:
            pass
        path.write_text(updated, encoding="utf-8")
        written.append(path)
    return written


@dataclass
class CloudProbe:
    ready: bool
    detail: str


def probe_cloud(settings: Any, tag: str = "kimi-k3:cloud", timeout: float = 12.0) -> CloudProbe:
    """Ask Ollama for one cloud model's details to learn the real state.

    Three outcomes matter: ready, cloud disabled, and sign-in required. The
    last one is not an error in this app's config, so it gets its own message.
    """
    if not cloud_enabled():
        return CloudProbe(False, "Ollama Cloud is disabled (sovereign cloud --enable)")
    import asyncio

    import httpx

    from .ollama import OllamaClient, OllamaError

    client = OllamaClient(settings.ollama_url, timeout=timeout)
    try:
        asyncio.run(client.show(tag))
    except OllamaError as exc:
        text = str(exc)
        lowered = text.lower()
        if "sign in" in lowered or "signin" in lowered or "unauthor" in lowered:
            return CloudProbe(False, "signed out — run: ollama signin")
        if plan_required(text):
            return CloudProbe(False, f"reachable, but needs an Ollama Pro plan: {PRO_UPGRADE}")
        if "cloud is disabled" in lowered:
            return CloudProbe(False, "Ollama Cloud is disabled (sovereign cloud --enable)")
        if "not found" in lowered:
            return CloudProbe(False, f"{tag} is not available to this account")
        return CloudProbe(False, text[:160])

    # Metadata can be listed even when generation is blocked by the account's
    # plan, so send one tiny completion: that is what actually returns 402.
    try:
        response = httpx.post(
            f"{settings.ollama_url.rstrip('/')}/api/chat",
            json={
                "model": tag,
                "messages": [{"role": "user", "content": "Reply with exactly: OK"}],
                "stream": False,
                "options": {"num_predict": 8, "temperature": 0},
            },
            timeout=httpx.Timeout(timeout, connect=3.0),
        )
    except httpx.HTTPError as exc:
        return CloudProbe(False, f"no answer in {timeout:.0f}s ({type(exc).__name__})")
    body = response.text
    if response.status_code == 402 or plan_required(body):
        return CloudProbe(False, f"needs an Ollama Pro plan: {PRO_UPGRADE}")
    if response.status_code >= 400:
        lowered = body.lower()
        if "cloud is disabled" in lowered:
            return CloudProbe(False, "Ollama Cloud is disabled (sovereign cloud --enable)")
        if "sign in" in lowered or "unauthor" in lowered:
            return CloudProbe(False, "signed out — run: ollama signin")
        return CloudProbe(False, f"HTTP {response.status_code}: {body[:140]}")
    return CloudProbe(True, f"{tag} answered a test prompt")


def requested_models() -> tuple[tuple[str, str, str], ...]:
    """(friendly name, Ollama tag, note) for the eight requested models."""
    return REQUESTED_CLOUD_MODELS


def status_lines(settings: Any) -> list[tuple[str, str]]:
    """(label, value) rows for the CLI, with readiness for each requested tag."""
    status = read_cloud_status()
    rows = [("Ollama Cloud", status.detail)]
    rows.append(("Cloud models", f"{len(CLOUD_TAGS)} tags · {len(ALIAS_TARGETS)} gateway aliases"))
    return rows


