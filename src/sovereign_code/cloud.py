def cloud_env_path() -> Path:
    return LOCAL_AI_ROOT / "gateway" / "cloud.env"


def shell_profile_path() -> Path:
    return Path.home() / ".config" / "sovereign-ai-os" / "profile.env"


def read_cloud_env(path: Path | None = None) -> dict[str, str]:
    """Parse the gateway's KEY=VALUE file without importing it into a shell."""
    target = path or cloud_env_path()
    try:
        text = target.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return {}
    values: dict[str, str] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip().removeprefix("export ").strip()
        value = value.strip().strip("'\"")
        if key and value:
            values[key] = value
    return values


def merged_env(env: dict[str, str] | None = None, env_path: Path | None = None) -> dict[str, str]:
    """Process env + cloud.env, with the process environment winning."""
    merged = read_cloud_env(env_path)
    merged.update(os.environ)
    if env:
        merged.update(env)
    return merged


def provider_key(provider: Provider, env: dict[str, str] | None = None) -> str:
    merged = merged_env(env)
    for name in provider.env_vars:
        value = merged.get(name, "")
        if value:
            return value
    return ""


def available_providers(env: dict[str, str] | None = None) -> tuple[str, ...]:
    merged = merged_env(env)
    return tuple(key for key, provider in PROVIDERS.items() if provider_key(provider, merged))


def masked(value: str) -> str:
    if not value:
        return ""
    if len(value) <= 8:
        return "…" + value[-2:]
    return value[:3] + "…" + value[-4:]


def provider_status(
    env: dict[str, str] | None = None,
) -> list[tuple[str, str, str, str]]:
    """(provider key, name, status, masked key/env var) for the CLI table."""
    merged = merged_env(env)
    rows: list[tuple[str, str, str, str]] = []
    for key, provider in PROVIDERS.items():
        value = provider_key(provider, merged)
        if value:
            rows.append((key, provider.name, "key set", masked(value)))
        else:
            rows.append((key, provider.name, "no key", provider.env_var))
    return rows


def set_provider_key(provider_key_name: str, value: str, path: Path | None = None) -> Path:
    """Store a provider key in cloud.env (mode 0600) for the gateway supervisor."""
    provider = PROVIDERS.get(provider_key_name)
    if provider is None:
        raise ValueError(f"unknown provider: {provider_key_name}")
    secret = value.strip()
    if not secret or "\n" in secret or "\r" in secret:
        raise ValueError("the key is empty or contains a newline")
    target = path or cloud_env_path()
    target.parent.mkdir(parents=True, exist_ok=True)
    lines: list[str] = []
    try:
        lines = target.read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeDecodeError):
        lines = []

    wanted = provider.env_var
    replaced = False
    output: list[str] = []
    for line in lines:
        stripped = line.strip()
        if stripped.startswith((f"{wanted}=", f"export {wanted}=")):
            output.append(f'{wanted}="{secret}"')
            replaced = True
        else:
            output.append(line)
    if not replaced:
        output.append(f'{wanted}="{secret}"')
    target.write_text("\n".join(output) + "\n", encoding="utf-8")
    target.chmod(0o600)
    return target


def _rewrite_shell_profile(path: Path, enabled: bool) -> bool:
    """Keep the sourced profile from re-disabling cloud in every new shell."""
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False
    marker = f'export OLLAMA_NO_CLOUD="{"0" if enabled else "1"}"'
    updated, count = re.subn(r'export\s+OLLAMA_NO_CLOUD=(["\']?)[01]\1', marker, text)
    if count == 0:
        return False
    old_note = "cloud opt-in" if not enabled else "cloud disabled"
    new_note = "cloud opt-in" if enabled else "cloud disabled"
    updated = updated.replace(
        f"Ollama: loopback only, {old_note}", f"Ollama: loopback only, {new_note}"
    )
    if updated == text:
        return False
    path.write_text(updated, encoding="utf-8")
    return True


