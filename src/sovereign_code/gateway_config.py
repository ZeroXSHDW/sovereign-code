@dataclass(frozen=True)
class ModelEntry:
    model_name: str
    litellm_model: str
    api_base: str
    num_ctx: int | None = None


def _entry(name: str, target: str, api_base: str, num_ctx: int | None = None) -> ModelEntry:
    return ModelEntry(name, target, api_base, num_ctx)


def _role_entries() -> list[ModelEntry]:
    entries: list[ModelEntry] = []
    for alias, route in ROLE_ALIASES.items():
        # Routes that are tier names get mapped to tier-gateway; direct tags go
        # to Ollama. The tier gateway resolves "auto/fast/balanced/deep/ultra".
        if route in {"fast", "balanced", "deep", "ultra", "auto"}:
            entries.append(_entry(alias, route, TIER_GATEWAY))
        else:
            max_ctx = (
                CATALOG.get(route, type("S", (), {"max_context": 32768})()).max_context
                if route in CATALOG
                else None
            )
            entries.append(_entry(alias, f"ollama/{route}", OLLAMA_DIRECT, max_ctx))
    return entries


def _direct_model_entries() -> list[ModelEntry]:
    """Every installed-capable catalog model as a direct alias."""
    entries: list[ModelEntry] = []
    for tag, spec in CATALOG.items():
        alias = f"local-{tag.replace(':', '-')}"
        entries.append(_entry(alias, f"ollama/{tag}", OLLAMA_DIRECT, spec.max_context))
    return entries


def _mlx_entries() -> list[ModelEntry]:
    """MLX aliases that route through the tier gateway to the mlx-lm server."""
    entries: list[ModelEntry] = []
    for alias in MLX_ALIASES:
        entries.append(_entry(alias, alias, TIER_GATEWAY))
    return entries


def render(cloud_block: str | None = None) -> str:
    """Render the local-only model_list YAML document."""
    lines: list[str] = [
        BLOCK_START,
        "# Sovereign Code - model list for every code agent.",
        "# Regenerate with: sovereign gateway-config --write",
        "# Edits outside this block are preserved.",
        "# Local-only: every model resolves to an installed Ollama model.",
        "model_list:",
    ]
    for entry in _role_entries() + _direct_model_entries() + _mlx_entries():
        lines.append(f"  - model_name: {entry.model_name}")
        lines.append("    litellm_params:")
        lines.append(f"      model: {entry.litellm_model}")
        lines.append(f"      api_base: {entry.api_base}")
        if entry.num_ctx:
            lines.append(f"      num_ctx: {entry.num_ctx}")
    if cloud_block:
        lines.append(cloud_block.rstrip("\n"))
    lines.append(f"  {BLOCK_END}")
    return "\n".join(lines) + "\n"


def default_path() -> Path:
    return LOCAL_AI_ROOT / "gateway" / "model_list.yaml"


def write(path: Path | None = None) -> Path:
    """Write the local model_list to disk (mode 0644) and return its path."""
    target = path or default_path()
    target.parent.mkdir(parents=True, exist_ok=True)
    text = render()
    target.write_text(text, encoding="utf-8")
    target.chmod(0o644)
    return target
