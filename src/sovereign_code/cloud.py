"""Ollama Cloud access for the frontier models.

Sovereign Code is local-first: nothing is routed to the internet unless the
user explicitly names a ``:cloud`` tag, a ``cloud-*`` gateway alias, or runs
``sovereign cloud --enable``. Ollama serves these models from ollama.com, so
prompts leave the Mac; the CLI says that before it does anything.

Two switches disable cloud access and both must be off:

* ``~/.ollama/server.json`` -> ``{"disable_ollama_cloud": true}`` (the app's
  persisted setting);
* ``OLLAMA_NO_CLOUD`` in the login/session environment (the launchd agent that
  tunes this Mac sets it to 1).

This module keeps the readiness checks and the gateway-config rendering pure so
they are testable. Only :func:`apply_cloud` and :func:`install_gateway_aliases`
touch the machine.
"""

